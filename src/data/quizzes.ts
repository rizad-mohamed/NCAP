export const questions: QuizQuestion[] = Object.entries(bank).flatMap(([moduleId, items]) =>
  items.map(([topic, difficulty, prompt, options, correctIndex, explanation], i) => ({
    id: `${moduleId}-qn-${String(i + 1).padStart(2, "0")}`,
    moduleId,
    topic,
    difficulty,
    prompt,
    options,
    correctIndex,
    explanation,
    status: "Published" as const,
  })),
);

export const getQuiz = (id: string) => quizzes.find((q) => q.id === id);
export const questionsForModule = (moduleId: string) => questions.filter((q) => q.moduleId === moduleId);
